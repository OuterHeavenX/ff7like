        hood = rgb(p["coat"])
        rect(d, x0 - 1, t - 2, x1 + 1, t + 2, hood)
        rect(d, x0, t - 3, x1, t - 2, shade(hood, 1.15))
        rect(d, x0, t + 2, x1, t + 3, hair)
