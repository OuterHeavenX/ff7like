def weapon_overlay(d, kind, hx, hy, angle, color=None):
    """Draws a small weapon held at (hx,hy). angle in degrees, 0 = pointing up."""
    if kind in ("none", None):
        return
    pal = {
        "blade": (rgb("#d8dde8"), rgb("#7a5a3a")), "wrench": (rgb("#a8b0b8"), rgb("#5a3a22")),
        "shield": (rgb("#6a86a8"), rgb("#c9b26b")), "staff": (rgb("#8a6a3a"), rgb("#9fe0d0")),
        "tome": (rgb("#6a2a3a"), rgb("#e6c86e")), "bow": (rgb("#7a5a2a"), rgb("#e8e0c8")),
        "lute": (rgb("#b07a3a"), rgb("#f6d85a")),
    }
    main, trim = pal.get(kind, (rgb("#cccccc"), rgb("#888888")))
    rad = math.radians(angle)
    dx, dy = math.sin(rad), -math.cos(rad)
    if kind == "shield":
        rect(d, hx - 3, hy - 4, hx + 1, hy + 3, main)
        rect(d, hx - 2, hy - 1, hx, hy, trim)
        return
    if kind == "tome":
        rect(d, hx - 3, hy - 3, hx + 1, hy + 1, main)
        rect(d, hx - 3, hy - 3, hx + 1, hy - 3, trim)
        return
    if kind == "lute":
        rect(d, hx - 3, hy - 1, hx + 1, hy + 3, main)
        for i in range(5):
            px(d, int(hx + dx * (i + 2)), int(hy + dy * (i + 2)), trim)
        return
    length = {"blade": 9, "wrench": 7, "staff": 12, "bow": 9}.get(kind, 8)
    for i in range(length):
        x = int(round(hx + dx * i))
        y = int(round(hy + dy * i))
        c = trim if i < 2 else main
        px(d, x, y, c)
        if kind == "wrench" and i == length - 1:
            rect(d, x - 1, y - 1, x + 1, y, main)
        if kind == "staff" and i == length - 1:
            rect(d, x - 1, y - 1, x + 1, y + 1, trim)
    if kind == "bow":
        for i in range(-4, 5):
            px(d, hx - 2 + abs(i) // 2, hy + i, main)


def battle_sheet(p):
    """8 frames 32x32 facing left: idle, ready, windup, strike, cast, hurt, ko, victory."""
    frames = []
    base_left = draw_char_frame(p, "left", 0)
    base_step = draw_char_frame(p, "left", 1)
    for idx in range(8):
        fr = Image.new("RGBA", (32, 32), CLEAR)
        d = ImageDraw.Draw(fr)
        ox, oy = 4, 0
        src = base_left
        wangle = -30
        hand = (13, 22)
        if idx == 1:      # ready
            oy = 1
            wangle = -60
        elif idx == 2:    # windup
            ox = 6
            wangle = 40
            hand = (15, 19)
        elif idx == 3:    # strike
            ox = 0
            src = base_step
            wangle = -100
            hand = (9, 22)
        elif idx == 4:    # cast
            wangle = -10
            hand = (11, 17)
        elif idx == 5:    # hurt
            ox = 7
        elif idx == 7:    # victory
            oy = -1
            wangle = 0
            hand = (12, 16)
        if idx == 6:      # KO: lying down
            lying = base_left.rotate(90, expand=True)
            fr.paste(lying, (0, 32 - 24), lying)
            d2 = ImageDraw.Draw(fr)
            frames.append(fr)
            continue
        fr.paste(src, (ox, oy), src)
        d = ImageDraw.Draw(fr)
        if idx != 5:
            weapon_overlay(d, p["weapon"], hand[0] + ox - 4, hand[1] + oy, wangle)
        if idx == 4:
            glow = rgb(p["accent"])
            for (gx, gy) in ((hand[0] + ox - 6, hand[1] - 3), (hand[0] + ox - 7, hand[1] - 1), (hand[0] + ox - 5, hand[1] - 5)):
                px(d, gx, gy, glow)
        if idx == 5:
            # hurt tint
            pxs = fr.load()
            for y in range(32):
                for x in range(32):
                    c = pxs[x, y]
                    if c[3] > 0 and c != OUTLINE:
                        pxs[x, y] = (min(255, c[0] + 60), int(c[1] * 0.75), int(c[2] * 0.75), 255)
        frames.append(outline(fr) if idx in (3, 4, 7) else fr)
    sheet = Image.new("RGBA", (32 * 8, 32), CLEAR)
    for i, f in enumerate(frames):
        sheet.paste(f, (i * 32, 0), f)
    return sheet


